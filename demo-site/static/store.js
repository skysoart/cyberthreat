// Global store logic
document.addEventListener('DOMContentLoaded', () => {
    updateCartCount();
    setupIntersectionObserver();
    
    // Account redirect logic if on /account
    if (window.location.pathname === '/account' || window.location.pathname === '/account.html') {
        if (!localStorage.getItem('session_user')) {
            window.location.href = '/login';
        } else {
            document.getElementById('userGreeting').textContent = localStorage.getItem('session_user');
        }
    }
});

// React-like mount animations for product cards
function setupIntersectionObserver() {
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
                observer.unobserve(entry.target); // only animate once
            }
        });
    }, {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    });

    // Wait a brief moment for products to be generated by inline scripts
    setTimeout(() => {
        document.querySelectorAll('.product-card').forEach((el, index) => {
            // Stagger effect
            el.style.transitionDelay = `${index * 50}ms`;
            observer.observe(el);
        });
    }, 50);
}

function addToCart(id) {
    let cart = JSON.parse(localStorage.getItem('cart') || '[]');
    cart.push(id);
    localStorage.setItem('cart', JSON.stringify(cart));
    
    updateCartCount(true); // pass true to trigger animation
    
    // Smooth button feedback
    const btn = event.currentTarget;
    const originalText = btn.textContent;
    btn.textContent = 'Added ✓';
    btn.style.background = '#10b981'; // success green
    
    setTimeout(() => {
        btn.textContent = originalText;
        btn.style.background = '';
    }, 1500);
}

function updateCartCount(animate = false) {
    const cart = JSON.parse(localStorage.getItem('cart') || '[]');
    const el = document.getElementById('cart-count');
    if (el) {
        el.textContent = cart.length;
        
        if (animate) {
            // Trigger CSS animation
            el.parentElement.classList.remove('cart-pop');
            void el.parentElement.offsetWidth; // trigger reflow
            el.parentElement.classList.add('cart-pop');
        }
    }
}

// Form Handlers
const loginForm = document.getElementById('loginForm');
if (loginForm) {
    loginForm.addEventListener('submit', async (e) => {
        e.preventDefault();
        const email = document.getElementById('email').value;
        const password = document.getElementById('password').value;
        const errorEl = document.getElementById('loginError');
        const submitBtn = e.target.querySelector('button[type="submit"]');
        
        // Loading state
        const ogText = submitBtn.textContent;
        submitBtn.textContent = 'Authenticating...';
        submitBtn.style.opacity = '0.8';
        
        try {
            const res = await fetch('/login', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ email, password })
            });
            
            if (res.ok) {
                localStorage.setItem('session_user', email);
                // Simple fade out before redirect
                document.body.style.opacity = '0';
                setTimeout(() => window.location.href = '/account', 300);
            } else {
                showError(errorEl, "Incorrect email or password");
                resetBtn(submitBtn, ogText);
            }
        } catch (err) {
            // Mock behavior if backend isn't running yet
            setTimeout(() => {
                if (password === 'demo1234' && ['alice@samplestore.test', 'bob@samplestore.test', 'carol@samplestore.test'].includes(email)) {
                    localStorage.setItem('session_user', email);
                    document.body.style.opacity = '0';
                    setTimeout(() => window.location.href = '/account', 300);
                } else {
                    showError(errorEl, "Incorrect email or password (Mock)");
                    resetBtn(submitBtn, ogText);
                }
            }, 600); // fake network delay
        }
    });
}

const registerForm = document.getElementById('registerForm');
